#!/bin/bash
# Задача 4. Все идентификаторы (правила C/C++/Java) в файле, без повторений.
# Идентификатор: буква или '_', далее буквы, цифры, '_'.

set -euo pipefail

if [ "$#" -ne 1 ]; then
    echo "Использование: $0 <файл>" >&2
    exit 1
fi

grep -oE '[A-Za-z_][A-Za-z_0-9]*' "$1" | sort -u | tr '\n' ' '
echo
