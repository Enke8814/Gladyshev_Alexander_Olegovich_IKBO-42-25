#!/bin/bash
# Задача 7. Поиск файлов-дубликатов по содержимому в каталоге и подкаталогах.
# Сравниваем не имена, а контрольные суммы MD5.
# Использование: ./task7.sh [каталог]

set -euo pipefail

dir="${1:-.}"

if [ ! -d "$dir" ]; then
    echo "Ошибка: '$dir' не каталог" >&2
    exit 1
fi

# md5sum печатает "<32 символа хеша>  <путь>".
# sort упорядочивает по хешу, uniq -w32 -D оставляет только повторяющиеся группы.
find "$dir" -type f -exec md5sum {} + \
    | sort \
    | uniq -w32 --all-repeated=separate
