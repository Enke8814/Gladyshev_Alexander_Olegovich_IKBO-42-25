#!/bin/bash
# Задача 9. Замена последовательностей из 4 пробелов на символ табуляции.
# Использование: ./task9.sh <входной_файл> <выходной_файл>

set -euo pipefail

if [ "$#" -ne 2 ]; then
    echo "Использование: $0 <входной_файл> <выходной_файл>" >&2
    exit 1
fi

src="$1"
dst="$2"

if [ ! -f "$src" ]; then
    echo "Ошибка: файл '$src' не найден" >&2
    exit 1
fi

sed 's/    /\t/g' "$src" > "$dst"

echo "Готово: $src -> $dst"
